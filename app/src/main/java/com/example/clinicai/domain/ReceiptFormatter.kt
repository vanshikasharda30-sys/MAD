package com.example.clinicai.domain

import com.example.clinicai.util.DateFormats
import com.example.clinicai.util.PrivacyMasker
import java.util.TimeZone

data class ReceiptRow(val label: String, val value: String, val emphasized: Boolean = false)

data class ReceiptSection(val title: String, val rows: List<ReceiptRow>)

/** The words and numbers on the receipt, independent of how they are drawn (screen or PDF). */
data class ReceiptDocument(
    val title: String,
    val subtitle: String,
    val statusLabel: String,
    val bookingId: String,
    val sections: List<ReceiptSection>,
    val notices: List<String>,
    val footer: String,
    val fileName: String,
)

object ReceiptFormatter {

    fun format(receipt: ReceiptData, zone: TimeZone = TimeZone.getDefault()): ReceiptDocument {
        val paid = receipt.hasPaidDeposit

        val booking = buildList {
            add(ReceiptRow("Booking ID", receipt.appointmentId, emphasized = true))
            DateFormats.timestamp(receipt.bookedAt, zone)?.let { add(ReceiptRow("Booked on", it)) }
            add(ReceiptRow("Status", statusText(receipt.status)))
        }

        val patient = buildList {
            receipt.patientName?.takeIf { it.isNotBlank() }?.let { add(ReceiptRow("Patient", it)) }
            val contact = listOfNotNull(
                PrivacyMasker.maskEmail(receipt.patientEmail),
                PrivacyMasker.maskPhone(receipt.patientPhone),
            ).joinToString(" · ")
            if (contact.isNotBlank()) add(ReceiptRow("Contact", contact))
        }

        val appointment = buildList {
            add(ReceiptRow("Doctor", receipt.doctorName, emphasized = true))
            receipt.qualification?.let { add(ReceiptRow("Qualification", it)) }
            receipt.specialization?.let { add(ReceiptRow("Specialty", it)) }
            add(ReceiptRow("Date & time", dateTimeText(receipt)))
            add(ReceiptRow("Type", if (receipt.isWalkIn) "Walk-in (live queue)" else "Scheduled appointment"))
            receipt.clinicName?.let { add(ReceiptRow("Clinic", it)) }
            receipt.clinicAddress?.let { add(ReceiptRow("Address", it)) }
            receipt.clinicPhone?.let { add(ReceiptRow("Clinic phone", it)) }
        }

        val charges = buildList {
            receipt.consultationFee?.let { add(ReceiptRow("Consultation fee (as listed)", "₹${DateFormats.rupees(it)}")) }
            val deposit = receipt.depositAmountPaise
            when {
                paid -> {
                    add(ReceiptRow("Deposit paid", "₹${DateFormats.rupeesFromPaise(deposit!!)}", emphasized = true))
                    DateFormats.timestamp(receipt.depositPaidAt, zone)?.let { add(ReceiptRow("Paid on", it)) }
                    receipt.paymentReference?.let { add(ReceiptRow("Payment reference", it)) }
                    add(ReceiptRow("Payment status", "Deposit paid"))
                }
                deposit != null -> {
                    add(ReceiptRow("Booking deposit", "₹${DateFormats.rupeesFromPaise(deposit)}"))
                    add(ReceiptRow("Payment status", if (receipt.depositStatus == "FAILED") "Deposit payment failed" else "Deposit not paid"))
                }
                else -> add(ReceiptRow("Payment status", "No online payment taken"))
            }
        }

        val sections = buildList {
            add(ReceiptSection("Booking", booking))
            if (patient.isNotEmpty()) add(ReceiptSection("Patient", patient))
            add(ReceiptSection("Appointment", appointment))
            add(ReceiptSection("Charges", charges))
            receipt.notes?.let { add(ReceiptSection("Visit notes", listOf(ReceiptRow("Shared with doctor", it)))) }
        }

        val notices = buildList {
            if (!paid) add("This is an appointment confirmation, not a payment receipt. No online payment has been taken for this booking; the consultation fee is shown for reference only.")
            add("You can cancel a confirmed appointment from My Appointments in the ClinicAI app.")
        }

        return ReceiptDocument(
            title = if (paid) "Booking Confirmation & Deposit Receipt" else "Booking Confirmation",
            subtitle = if (paid) "Appointment confirmation with booking-deposit payment" else "Appointment confirmation — not a payment receipt",
            statusLabel = statusText(receipt.status).uppercase(),
            bookingId = receipt.appointmentId,
            sections = sections,
            notices = notices,
            footer = "Generated by the ClinicAI app from your confirmed booking.",
            fileName = "ClinicAI-Booking-${receipt.appointmentId.filter { it.isLetterOrDigit() }.take(24)}.pdf",
        )
    }

    fun statusText(status: String): String = when (status) {
        "confirmed" -> "Confirmed"
        "cancelled" -> "Cancelled"
        "completed" -> "Completed"
        "no_show" -> "No-show"
        "in_consultation" -> "In consultation"
        else -> status.replace('_', ' ').replaceFirstChar { it.uppercase() }
    }

    private fun dateTimeText(receipt: ReceiptData): String {
        val date = DateFormats.longDate(receipt.date)
        return receipt.startTime?.let { "$date · ${DateFormats.time12h(it)}" } ?: "$date (walk-in)"
    }
}
